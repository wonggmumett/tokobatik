alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.profiles enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

grant select on public.categories to anon,authenticated;
grant select on public.products to anon,authenticated;
grant select on public.profiles to authenticated;
grant select,insert,update,delete on public.products to authenticated;
grant select,insert on public.orders to anon,authenticated;
grant select,insert on public.order_items to anon,authenticated;
grant update on public.orders to authenticated;
grant usage,select on all sequences in schema public to anon,authenticated;

drop policy if exists "Public can read categories" on public.categories;
create policy "Public can read categories" on public.categories for select to anon,authenticated using(true);

drop policy if exists "Public can read products" on public.products;
create policy "Public can read products" on public.products for select to anon,authenticated using(true);

drop policy if exists "Users read own profile" on public.profiles;
create policy "Users read own profile" on public.profiles for select to authenticated using(id=auth.uid());

drop policy if exists "Customers create orders" on public.orders;
create policy "Customers create orders" on public.orders for insert to anon,authenticated with check(true);

drop policy if exists "Admins read orders" on public.orders;
create policy "Admins read orders" on public.orders for select to authenticated
using(exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders" on public.orders for update to authenticated
using(exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'))
with check(exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

drop policy if exists "Customers create order items" on public.order_items;
create policy "Customers create order items" on public.order_items for insert to anon,authenticated with check(true);

drop policy if exists "Admins read order items" on public.order_items;
create policy "Admins read order items" on public.order_items for select to authenticated
using(exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products for all to authenticated
using(exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'))
with check(exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

insert into storage.buckets(id,name,public) values('product-images','product-images',true)
on conflict(id) do update set public=true;

drop policy if exists "Public read product images" on storage.objects;
create policy "Public read product images" on storage.objects for select to public using(bucket_id='product-images');

drop policy if exists "Admins upload product images" on storage.objects;
create policy "Admins upload product images" on storage.objects for insert to authenticated
with check(bucket_id='product-images' and exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

drop policy if exists "Admins update product images" on storage.objects;
create policy "Admins update product images" on storage.objects for update to authenticated
using(bucket_id='product-images' and exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

drop policy if exists "Admins delete product images" on storage.objects;
create policy "Admins delete product images" on storage.objects for delete to authenticated
using(bucket_id='product-images' and exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

