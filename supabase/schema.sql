-- NUSANTARA BATIK
-- Struktur backend mengikuti tabel toko di WEBSITE_WARIH.
create extension if not exists pgcrypto;

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null, slug text not null unique, image text default '',
  description text default '', created_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null, category text not null,
  price numeric(12,2) not null default 0 check (price >= 0),
  description text default '', sizes text[] not null default '{}',
  stock integer not null default 0 check (stock >= 0),
  image text default '', featured boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text default '', role text not null default 'customer'
    check (role in ('admin','customer')), created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_name text not null, phone text not null, address text not null,
  total numeric(12,2) not null default 0 check (total >= 0),
  status text not null default 'pending'
    check (status in ('pending','confirmed','processing','shipped','completed','cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null, price numeric(12,2) not null default 0,
  size text not null, quantity integer not null default 1 check (quantity > 0), image text default ''
);

